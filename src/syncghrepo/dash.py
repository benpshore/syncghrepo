"""gh-dash config: review your PRs and issues across the discovered repos in gh dash.

syncghrepo only writes the YAML; it never launches the gh dash TUI. Every run writes
or refreshes ~/.config/gh-dash/config.yml (or $XDG_CONFIG_HOME/gh-dash) when no
file is there or the file there is one syncghrepo generated (its first line is
HEADER). Your own config.yml is never touched: then the config goes next to it as
config.syncghrepo.yml (use it with: gh dash --config <path>).
"""

import json
import os
from pathlib import Path

from .local import short_path

PR_SECTIONS = (
    ("My open PRs", "is:open author:@me draft:false"),
    ("My drafts", "is:open author:@me draft:true"),
    ("Review requested", "is:open review-requested:@me"),
)
ISSUE_SECTIONS = (("Assigned to me", "is:open assignee:@me"),)
HEADER = "# Generated by syncghrepo"


def config_dir() -> Path:
    xdg = os.environ.get("XDG_CONFIG_HOME")
    return (Path(xdg) if xdg else Path.home() / ".config") / "gh-dash"


def generated(path: Path) -> bool:
    """Whether path is a regular file syncghrepo wrote (safe to refresh)."""
    try:
        if path.is_symlink() or not path.is_file():
            return False
        with path.open("rb") as file:
            return file.read(len(HEADER)) == HEADER.encode()
    except OSError:
        return False


def target() -> tuple[Path, bool]:
    """(where to write, whether a config.yml of your own is there)."""
    main = config_dir() / "config.yml"
    yours = (main.exists() or main.is_symlink()) and not generated(main)
    return (main.with_name("config.syncghrepo.yml") if yours else main), yours


def render(repos: list[dict], stamp: str, version: str) -> str:
    """gh-dash YAML (JSON-quoted scalars, which YAML reads as-is) for these repos."""
    names = sorted(
        {entry["name"] for entry in repos if entry["github"] and not entry["archived"]},
        key=str.lower,
    )
    scope = "".join(f" repo:{name}" for name in names)
    q = json.dumps
    lines = [
        f"{HEADER} {version} at {stamp} from {len(names)} repos; refreshed every run.",
        "# Open it with: gh dash (or gh dash --config <this file>).",
        "prSections:",
    ]
    for title, filters in PR_SECTIONS:
        lines += [f"  - title: {q(title)}", f"    filters: {q(filters + scope)}"]
    lines.append("issuesSections:")
    for title, filters in ISSUE_SECTIONS:
        lines += [f"  - title: {q(title)}", f"    filters: {q(filters + scope)}"]
    paths = {
        entry["name"]: short_path(entry["clones"][0]["path"])
        for entry in repos
        if entry["github"] and entry["clones"]
    }
    if paths:
        lines.append("repoPaths:")  # lets gh dash check out a PR in your clone
        lines += [f"  {q(name)}: {q(paths[name])}" for name in sorted(paths, key=str.lower)]
    lines += ["defaults:", "  view: prs", ""]
    return "\n".join(lines)


def save(repos: list[dict], stamp: str, version: str, write: bool) -> dict:
    """Write the config (only if write) and say where it is or would be."""
    path, existing = target()
    if write:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(repos, stamp, version))
    return {"path": str(path), "written": write, "existing_config": existing}
